//! What setup pins for a protected install, how an enforcer finds it, and
//! the install id every enforcer derives from its own identity.
//!
//! Setup writes three values: the signer list fingerprint, the install's
//! prefix and the release channel it follows. The project is the one signer
//! list version 1 names. Nothing else comes from setup, and nothing at all
//! from the control plane.

use std::fmt;

use alien_error::AlienError;
use serde::{Deserialize, Serialize};

use crate::error::{ErrorData, Result};
use crate::signer_list::is_fingerprint;

/// The signing settings of one install.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct SigningSettings {
    /// `SHA256:<hex>` fingerprint of the project's signer list version 1.
    pub fingerprint: String,
    /// The install's resource prefix. It must equal the place the settings
    /// were found, so a value copied from a neighbor is refused.
    pub prefix: String,
    /// Release channel the install follows. A release for another channel is
    /// refused.
    pub channel: String,
}

impl SigningSettings {
    /// Parse settings found at `prefix` and check each field.
    pub fn parse(bytes: &[u8], prefix: &str) -> Result<Self> {
        let settings: SigningSettings =
            serde_json::from_slice(bytes).map_err(|error| invalid(format!("{error}")))?;
        settings.validate()?;
        if settings.prefix != prefix {
            return Err(invalid(format!(
                "the settings found for '{prefix}' name prefix '{}'",
                settings.prefix
            )));
        }
        Ok(settings)
    }

    /// Check each field.
    pub fn validate(&self) -> Result<()> {
        if !is_fingerprint(&self.fingerprint) {
            return Err(invalid(format!(
                "fingerprint '{}' is not SHA256:<64 lowercase hex>",
                self.fingerprint
            )));
        }
        if !is_prefix(&self.prefix) {
            return Err(invalid(format!(
                "prefix '{}' is not 1 to 63 of [A-Za-z0-9-] starting with a letter",
                self.prefix
            )));
        }
        if !is_name(&self.channel, 63) {
            return Err(invalid(format!(
                "channel '{}' is not 1 to 63 of [a-z0-9-]",
                self.channel
            )));
        }
        Ok(())
    }

    /// The JSON setup writes.
    pub fn to_json(&self) -> String {
        serde_json::to_string(self).expect("settings always serialize")
    }
}

/// The install id. Enforcers derive it from their own identity and never
/// read it from anywhere the control plane writes, so a statement signed for
/// one customer's install is refused by another's.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum InstallId {
    /// `aws:<account>:<region>:<prefix>`.
    Aws {
        /// 12-digit account id.
        account: String,
        /// Region.
        region: String,
        /// Stack prefix.
        prefix: String,
    },
    /// `gcp:<project>:<prefix>`.
    Gcp {
        /// Project id.
        project: String,
        /// Resource prefix.
        prefix: String,
    },
    /// `azure:<subscription>:<resource-group>`.
    Azure {
        /// Subscription id.
        subscription: String,
        /// Resource group.
        resource_group: String,
    },
    /// `k8s:<kube-system namespace uid>:<namespace>/<release>`.
    Kubernetes {
        /// UID of the cluster's `kube-system` namespace.
        cluster: String,
        /// Install namespace.
        namespace: String,
        /// Helm release name.
        release: String,
    },
    /// `machine:<uuid>`, generated by `join` on the machine itself.
    Machine {
        /// UUID.
        id: String,
    },
}

impl fmt::Display for InstallId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Aws {
                account,
                region,
                prefix,
            } => write!(f, "aws:{account}:{region}:{prefix}"),
            Self::Gcp { project, prefix } => write!(f, "gcp:{project}:{prefix}"),
            Self::Azure {
                subscription,
                resource_group,
            } => write!(f, "azure:{subscription}:{resource_group}"),
            Self::Kubernetes {
                cluster,
                namespace,
                release,
            } => write!(f, "k8s:{cluster}:{namespace}/{release}"),
            Self::Machine { id } => write!(f, "machine:{id}"),
        }
    }
}

impl InstallId {
    /// Parse the printed form, checking each part, so an id the CLI shows an
    /// admin is the one an enforcer would derive.
    pub fn parse(text: &str) -> Result<Self> {
        let bad = || invalid_install(text);
        let (kind, rest) = text.split_once(':').ok_or_else(bad)?;
        let parts: Vec<&str> = rest.split(':').collect();
        let id = match (kind, parts.as_slice()) {
            ("aws", [account, region, prefix]) => Self::Aws {
                account: account.to_string(),
                region: region.to_string(),
                prefix: prefix.to_string(),
            },
            ("gcp", [project, prefix]) => Self::Gcp {
                project: project.to_string(),
                prefix: prefix.to_string(),
            },
            ("azure", [subscription, resource_group]) => Self::Azure {
                subscription: subscription.to_string(),
                resource_group: resource_group.to_string(),
            },
            ("k8s", [cluster, scoped]) => {
                let (namespace, release) = scoped.split_once('/').ok_or_else(bad)?;
                Self::Kubernetes {
                    cluster: cluster.to_string(),
                    namespace: namespace.to_string(),
                    release: release.to_string(),
                }
            }
            ("machine", [id]) => Self::Machine { id: id.to_string() },
            _ => return Err(bad()),
        };
        id.validate()?;
        Ok(id)
    }

    /// Check each part.
    pub fn validate(&self) -> Result<()> {
        let ok = match self {
            Self::Aws {
                account,
                region,
                prefix,
            } => {
                account.len() == 12
                    && account.bytes().all(|byte| byte.is_ascii_digit())
                    && is_name(region, 32)
                    && is_prefix(prefix)
            }
            Self::Gcp { project, prefix } => is_name(project, 30) && is_prefix(prefix),
            Self::Azure {
                subscription,
                resource_group,
            } => {
                is_uuid(subscription)
                    && !resource_group.is_empty()
                    && resource_group.len() <= 90
                    && resource_group.bytes().all(|byte| {
                        byte.is_ascii_alphanumeric()
                            || matches!(byte, b'-' | b'_' | b'.' | b'(' | b')')
                    })
            }
            Self::Kubernetes {
                cluster,
                namespace,
                release,
            } => is_uuid(cluster) && is_name(namespace, 63) && is_name(release, 53),
            Self::Machine { id } => is_uuid(id),
        };
        if ok {
            Ok(())
        } else {
            Err(invalid_install(&self.to_string()))
        }
    }
}

/// What an enforcer got when it read one place the settings could be.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Lookup {
    /// The value was there.
    Found(Vec<u8>),
    /// The place is empty.
    Absent,
    /// The enforcer may not read it.
    Denied,
}

/// Decide whether an install is protected from every place its settings
/// could be, keyed by the prefix each place belongs to.
///
/// Every candidate must be read; this never stops at the first answer. The
/// install is protected if exactly one place holds settings and they name
/// that place's prefix. Two or more, or settings that don't parse, are an
/// error. It is unprotected only if every place is absent or denied and at
/// least one is absent: when every place is denied, nothing was learned.
pub fn discover(candidates: &[(String, Lookup)]) -> Result<Option<SigningSettings>> {
    if candidates.is_empty() {
        return Err(undecided("there was no place to look for the settings"));
    }
    let mut found = Vec::new();
    let mut any_absent = false;
    for (prefix, lookup) in candidates {
        match lookup {
            Lookup::Found(bytes) => found.push(SigningSettings::parse(bytes, prefix)?),
            Lookup::Absent => any_absent = true,
            Lookup::Denied => {}
        }
    }
    match found.len() {
        0 if any_absent => Ok(None),
        0 => Err(undecided(
            "every place the settings could be refused the read",
        )),
        1 => Ok(found.pop()),
        count => Err(undecided(format!(
            "{count} places hold signing settings: {}",
            found
                .iter()
                .map(|settings| settings.prefix.as_str())
                .collect::<Vec<_>>()
                .join(", ")
        ))),
    }
}

/// The prefixes a resource name could belong to, longest first: the name
/// itself, then every part of it ending before a `-`. An enforcer whose role
/// is `acme-prod-verifier` looks for settings of `acme-prod-verifier`,
/// `acme-prod` and `acme`.
pub fn candidate_prefixes(name: &str) -> Vec<String> {
    let mut prefixes = vec![name.to_string()];
    let mut rest = name;
    while let Some((head, _)) = rest.rsplit_once('-') {
        if !head.is_empty() {
            prefixes.push(head.to_string());
        }
        rest = head;
    }
    prefixes
}

fn is_name(text: &str, max: usize) -> bool {
    (1..=max).contains(&text.len())
        && text
            .bytes()
            .all(|byte| matches!(byte, b'a'..=b'z' | b'0'..=b'9' | b'-'))
        && !text.starts_with('-')
}

/// Resource prefixes: CloudFormation stack names allow upper case.
fn is_prefix(text: &str) -> bool {
    (1..=63).contains(&text.len())
        && text.as_bytes()[0].is_ascii_alphabetic()
        && text
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-')
}

fn is_uuid(text: &str) -> bool {
    text.len() == 36
        && text.bytes().enumerate().all(|(index, byte)| match index {
            8 | 13 | 18 | 23 => byte == b'-',
            _ => byte.is_ascii_hexdigit() && !byte.is_ascii_uppercase(),
        })
}

fn invalid(reason: impl Into<String>) -> AlienError<ErrorData> {
    AlienError::new(ErrorData::SettingsInvalid {
        reason: reason.into(),
    })
}

fn invalid_install(text: &str) -> AlienError<ErrorData> {
    invalid(format!("'{text}' is not an install id"))
}

fn undecided(reason: impl Into<String>) -> AlienError<ErrorData> {
    AlienError::new(ErrorData::SettingsUndecided {
        reason: reason.into(),
    })
}

/// Where setup writes the signing settings, the ledger and deployer inputs.
///
/// Every name sits under a root no management grant reaches: grants are on
/// `<prefix>-*`, and these start with `/signed/` or `signed-`, so a neighbor
/// install whose prefix overlaps this one's can't write them.
pub mod names {
    /// AWS SSM parameter holding the signing settings.
    pub fn aws_settings(prefix: &str) -> String {
        format!("/signed/{prefix}/fingerprint")
    }

    /// AWS SSM parameter holding the ledger.
    pub fn aws_ledger(prefix: &str) -> String {
        format!("/signed/{prefix}/state")
    }

    /// AWS SSM path under which each deployer input is one parameter.
    pub fn aws_inputs(prefix: &str) -> String {
        format!("/signed/{prefix}/inputs/")
    }

    /// GCP Parameter Manager parameter holding the signing settings.
    pub fn gcp_settings(prefix: &str) -> String {
        format!("signed-{prefix}-fingerprint")
    }

    /// GCP Parameter Manager parameter holding the ledger.
    pub fn gcp_ledger(prefix: &str) -> String {
        format!("signed-{prefix}-state")
    }

    /// GCP Secret Manager secret holding deployer input `name`.
    pub fn gcp_input(prefix: &str, name: &str) -> String {
        format!("signed-{prefix}-input-{name}")
    }

    /// Azure resource-group tag holding the signing settings.
    pub const AZURE_SETTINGS_TAG: &str = "signing-fingerprint";

    /// Azure Key Vault secret, in the install's inputs vault, holding the ledger.
    pub const AZURE_LEDGER_SECRET: &str = "signing-state";

    /// Kubernetes ConfigMap holding the signing settings of Helm release `release`.
    pub fn kubernetes_settings(release: &str) -> String {
        format!("{release}-signing")
    }
}
