use crate::error::{ErrorData, Result};
use crate::resource::{ResourceDefinition, ResourceOutputsDefinition, ResourceRef, ResourceType};
use alien_error::AlienError;
use bon::Builder;
use serde::{Deserialize, Serialize};
use std::any::Any;
use std::fmt::Debug;

/// An operator-owned, invoke-only Lambda that runs pushed
/// `<plugin>/<operation>` operation commands.
///
/// Unlike [`crate::resources::Worker`], this resource is never declared by a
/// customer's stack config — the manager injects it into a push-mode-eligible
/// AWS deployment's desired stack on every reconcile pass (never persisted to
/// the release/stack record), so the resource executor provisions and tears
/// it down with the same credentials, retry, and state-machine guarantees as
/// any other resource. It has no triggers, public endpoints, or VPC config:
/// callers invoke it directly via `lambda:Invoke`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Builder)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
#[builder(start_fn = new)]
pub struct OperationsWorker {
    /// Identifier for the operations worker. Reserved id used by the manager
    /// when injecting this resource; must match
    /// `OPERATIONS_COMMAND_TARGET_ID` in `alien-commands`.
    #[builder(start_fn)]
    pub id: String,
    /// The `operations-worker` container image (digest-pinned).
    pub image: String,
}

impl OperationsWorker {
    /// The resource type identifier for the operations worker.
    pub const RESOURCE_TYPE: ResourceType = ResourceType::from_static("operations_worker");

    /// Returns the operations worker's unique identifier.
    pub fn id(&self) -> &str {
        &self.id
    }
}

/// Outputs generated by a successfully provisioned operations worker.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[cfg_attr(feature = "openapi", derive(utoipa::ToSchema))]
#[serde(rename_all = "camelCase")]
pub struct OperationsWorkerOutputs {
    /// The platform-specific function name.
    pub function_name: String,
    /// The ARN or platform-specific identifier.
    pub identifier: Option<String>,
}

impl ResourceOutputsDefinition for OperationsWorkerOutputs {
    fn get_resource_type(&self) -> ResourceType {
        OperationsWorker::RESOURCE_TYPE.clone()
    }

    fn as_any(&self) -> &dyn Any {
        self
    }

    fn box_clone(&self) -> Box<dyn ResourceOutputsDefinition> {
        Box::new(self.clone())
    }

    fn outputs_eq(&self, other: &dyn ResourceOutputsDefinition) -> bool {
        other.as_any().downcast_ref::<OperationsWorkerOutputs>() == Some(self)
    }

    fn to_json_value(&self) -> serde_json::Result<serde_json::Value> {
        serde_json::to_value(self)
    }
}

impl ResourceDefinition for OperationsWorker {
    fn get_resource_type(&self) -> ResourceType {
        Self::RESOURCE_TYPE
    }

    fn id(&self) -> &str {
        &self.id
    }

    fn get_dependencies(&self) -> Vec<ResourceRef> {
        Vec::new()
    }

    fn validate_update(&self, new_config: &dyn ResourceDefinition) -> Result<()> {
        let Some(new) = new_config.as_any().downcast_ref::<OperationsWorker>() else {
            return Err(AlienError::new(ErrorData::InvalidResourceUpdate {
                resource_id: self.id.clone(),
                reason: "New config is not an OperationsWorker".to_string(),
            }));
        };
        // Any image change is a valid in-place update — the Lambda's code is
        // simply updated to point at the new digest-pinned image.
        let _ = new;
        Ok(())
    }

    fn as_any(&self) -> &dyn Any {
        self
    }

    fn as_any_mut(&mut self) -> &mut dyn Any {
        self
    }

    fn box_clone(&self) -> Box<dyn ResourceDefinition> {
        Box::new(self.clone())
    }

    fn resource_eq(&self, other: &dyn ResourceDefinition) -> bool {
        other.as_any().downcast_ref::<OperationsWorker>() == Some(self)
    }

    fn to_json_value(&self) -> serde_json::Result<serde_json::Value> {
        serde_json::to_value(self)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_operations_worker_creation() {
        let worker = OperationsWorker::new("operations".to_string())
            .image("123.dkr.ecr.us-east-1.amazonaws.com/operations-worker@sha256:abc".to_string())
            .build();
        assert_eq!(worker.id, "operations");
    }

    #[test]
    fn image_change_is_a_valid_update() {
        let original = OperationsWorker::new("operations".to_string())
            .image("...@sha256:old".to_string())
            .build();
        let updated = OperationsWorker::new("operations".to_string())
            .image("...@sha256:new".to_string())
            .build();
        assert!(original.validate_update(&updated).is_ok());
    }
}
