//! Values Alien generates for secret stack inputs (`generate` on the input).
//!
//! A generated value is created once, when a deployment record is created, and
//! stored with the deployment's other input values. Later writes carry the
//! stored value forward instead of generating again, so it never rotates
//! behind the developer's back. An explicitly provided value always wins.

use std::collections::HashMap;

use alien_core::{Platform, StackInputDefinition, StackInputGenerate};
use rand::distr::{Alphanumeric, SampleString};

/// Generated inputs that apply to `platform`.
fn generated_inputs(
    inputs: &[StackInputDefinition],
    platform: Platform,
) -> impl Iterator<Item = (&StackInputDefinition, &StackInputGenerate)> {
    inputs.iter().filter_map(move |input| {
        let generate = input.generate.as_ref()?;
        let applies = input
            .platforms
            .as_ref()
            .is_none_or(|platforms| platforms.contains(&platform));
        applies.then_some((input, generate))
    })
}

/// A new alphanumeric value from the thread-local CSPRNG.
fn generate_value(generate: &StackInputGenerate) -> String {
    Alphanumeric.sample_string(&mut rand::rng(), generate.length as usize)
}

/// For a deployment being created: gives every generated input that has no
/// value in `values` a freshly generated one.
pub fn generate_missing_input_values(
    inputs: &[StackInputDefinition],
    platform: Platform,
    values: &mut HashMap<String, serde_json::Value>,
) {
    for (input, generate) in generated_inputs(inputs, platform) {
        values
            .entry(input.id.clone())
            .or_insert_with(|| serde_json::Value::String(generate_value(generate)));
    }
}

/// For a write that replaces an existing deployment's input values: keeps the
/// value the deployment already stores for every generated input `values`
/// does not set. Never generates — a missing stored value means another
/// control plane owns the secret, and inventing one here would replace it.
pub fn carry_stored_generated_input_values(
    inputs: &[StackInputDefinition],
    platform: Platform,
    stored: &HashMap<String, serde_json::Value>,
    values: &mut HashMap<String, serde_json::Value>,
) {
    for (input, _) in generated_inputs(inputs, platform) {
        if values.contains_key(&input.id) {
            continue;
        }
        if let Some(value) = stored.get(&input.id) {
            values.insert(input.id.clone(), value.clone());
        }
    }
}

/// Refuses values for generated inputs from a caller that may only provide
/// deployer inputs, such as a setup artifact's registration.
pub fn reject_generated_input_values(
    inputs: &[StackInputDefinition],
    values: &HashMap<String, serde_json::Value>,
) -> crate::error::Result<()> {
    match inputs
        .iter()
        .find(|input| input.is_generated() && values.contains_key(&input.id))
    {
        Some(input) => Err(crate::error::ErrorData::bad_request(format!(
            "Stack input '{}' is generated by Alien and cannot be set by setup",
            input.id
        ))),
        None => Ok(()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use alien_core::{StackInputKind, StackInputProvider};

    fn generated(id: &str, length: u32, platforms: Option<Vec<Platform>>) -> StackInputDefinition {
        StackInputDefinition {
            id: id.to_string(),
            kind: StackInputKind::Secret,
            provided_by: vec![StackInputProvider::Developer],
            required: true,
            label: "Signing key".to_string(),
            description: "Key the service signs internal tokens with.".to_string(),
            placeholder: None,
            default: None,
            platforms,
            validation: None,
            generate: Some(StackInputGenerate { length }),
            env: vec![],
        }
    }

    #[test]
    fn creation_generates_alphanumeric_values_of_the_declared_length() {
        let inputs = vec![
            generated("signingKey", 64, None),
            generated("gcpOnly", 32, Some(vec![Platform::Gcp])),
        ];
        let mut first = HashMap::new();
        generate_missing_input_values(&inputs, Platform::Aws, &mut first);
        let mut second = HashMap::new();
        generate_missing_input_values(&inputs, Platform::Aws, &mut second);

        let value = first["signingKey"].as_str().expect("a string value");
        assert_eq!(value.len(), 64);
        assert!(value.bytes().all(|byte| byte.is_ascii_alphanumeric()));
        assert_ne!(
            first["signingKey"], second["signingKey"],
            "each deployment gets its own value"
        );
        assert!(
            !first.contains_key("gcpOnly"),
            "inputs for other platforms are skipped"
        );
    }

    #[test]
    fn creation_keeps_an_explicit_value() {
        let inputs = vec![generated("signingKey", 64, None)];
        let mut values = HashMap::from([(
            "signingKey".to_string(),
            serde_json::json!("provided-by-developer-0123456789"),
        )]);
        generate_missing_input_values(&inputs, Platform::Aws, &mut values);
        assert_eq!(values["signingKey"], "provided-by-developer-0123456789");
    }

    #[test]
    fn rewrites_carry_the_stored_value_and_never_generate() {
        let inputs = vec![
            generated("signingKey", 64, None),
            generated("addedLater", 32, None),
        ];
        let mut stored = HashMap::new();
        generate_missing_input_values(&inputs[..1], Platform::Aws, &mut stored);

        let mut rewrite = HashMap::from([("region".to_string(), serde_json::json!("us-east-1"))]);
        carry_stored_generated_input_values(&inputs, Platform::Aws, &stored, &mut rewrite);

        assert_eq!(rewrite["signingKey"], stored["signingKey"]);
        assert!(!rewrite.contains_key("addedLater"));
        assert_eq!(rewrite["region"], "us-east-1");
    }
}
