/// Ensures the stack contains only allowed user-defined resource types and IDs.
///
/// Some resources like `AzureResourceGroup` and `RemoteStackManagement`
/// are system-managed and should not be manually added. A custom resource is allowed when exactly
/// one extension in the stack declares its type.
///
/// Note: While most ServiceAccounts are auto-generated by mutations (one per permission profile),
/// users CAN manually define ServiceAccounts for special cases like cross-account impersonation.
pub struct AllowedUserResourcesCheck;

#[async_trait::async_trait]
impl CompileTimeCheck for AllowedUserResourcesCheck {
    fn description(&self) -> &'static str {
        "Stack should contain only allowed user-defined resource types and IDs"
    }

    fn should_run(&self, _stack: &Stack, _platform: Platform) -> bool {
        true // Always run this check
    }

    async fn check(&self, stack: &Stack, platform: Platform) -> Result<CheckResult> {
        let allowed_user_types = HashSet::from([
            "worker",
            "daemon",
            "storage",
            "artifact-registry",
            "build",
            "queue",
            "kv",
            "vault",
            "key",
            "container",
            "service-account",
            // Customer-declarable to express pool/capacity-group config
            // (instance type, sizing, nestedVirtualization). Auto-generated
            // by the ComputeClusterMutation when not declared.
            "compute-cluster",
            "postgres",
            "redis",
            "ai",
            "email",
            "sandbox",
            "experimental/aws-opensearch",
        ]);
        let mut errors = Vec::new();
        if has_internet_sandbox(stack)
            && stack
                .permissions
                .profiles
                .contains_key(SANDBOX_EGRESS_GATEWAY_ID)
        {
            errors.push(
                "The sandbox gateway permission profile is reserved for preflight".to_string(),
            );
        }

        // A grant scoped to the bundle bucket would reach it past its write guard.
        let management_profile = match &stack.permissions.management {
            ManagementPermissions::Extend(profile) | ManagementPermissions::Override(profile) => {
                Some(("management", profile))
            }
            ManagementPermissions::Auto => None,
        };
        for (profile_name, profile) in stack
            .permissions
            .profiles
            .iter()
            .map(|(name, profile)| (name.as_str(), profile))
            .chain(management_profile)
        {
            for scope in profile.0.keys() {
                if scope.starts_with(SANDBOX_BUNDLE_STORAGE_ID) {
                    errors.push(format!(
                        "Permission profile '{profile_name}' grants on '{scope}', which is reserved for the bucket sandbox images are built from"
                    ));
                }
            }
        }

        let mut custom_resources: IndexMap<ResourceType, Vec<&str>> = IndexMap::new();
        for (resource_id, resource_entry) in stack.resources() {
            let resource_type_value = resource_entry.config.resource_type();
            let resource_type = resource_type_value.0.as_ref();
            let configured_id = resource_entry.config.id();

            if resource_id != configured_id {
                errors.push(format!(
                    "Resource map key '{resource_id}' does not match its configured ID '{configured_id}'"
                ));
                continue;
            }

            if matches!(
                resource_id.as_str(),
                SECRETS_VAULT_ID | DEPLOYER_SECRETS_VAULT_ID
            ) {
                errors.push(format!(
                    "Resource ID '{resource_id}' is reserved for deployment secret delivery. Choose a different ID for the application resource"
                ));
                continue;
            }

            // The bundle bucket's grants and its write guard are bound to this name as a prefix.
            if resource_id.starts_with(SANDBOX_BUNDLE_STORAGE_ID) {
                errors.push(format!(
                    "Resource ID '{resource_id}' starts with '{SANDBOX_BUNDLE_STORAGE_ID}', which is reserved for the bucket sandbox images are built from. Choose a different ID for the application resource"
                ));
                continue;
            }

            // Log consumers treat this resource as Alien's own (`is_managed_gateway`), so an
            // application resource must never hold the id while it is reserved.
            if is_managed_gateway(stack, resource_id) {
                errors.push(format!(
                    "Resource ID '{resource_id}' is reserved for the sandbox gateway"
                ));
                continue;
            }
            let normalized_id = resource_id.replace('_', "-").to_ascii_lowercase();
            if resource_type == "vault"
                && (normalized_id == DEPLOYER_SECRETS_VAULT_ID
                    || normalized_id.starts_with(&format!("{DEPLOYER_SECRETS_VAULT_ID}-"))
                    || DEPLOYER_SECRETS_VAULT_ID.starts_with(&format!("{normalized_id}-")))
            {
                errors.push(format!(
                    "Vault ID '{resource_id}' overlaps the reserved 'deployer-secrets' vault prefix. Choose a different ID so its values do not overlap customer deployer slots"
                ));
                continue;
            }

            if resource_entry
                .config
                .downcast_ref::<CustomResource>()
                .is_some()
            {
                custom_resources
                    .entry(resource_type_value.clone())
                    .or_default()
                    .push(resource_id);
                continue;
            }

            let is_allowed_user_type = allowed_user_types.contains(resource_type);

            // An extension's identity is made by Alien for the extension's own sets and trusted
            // by the manager; a stack can't declare one. The test platform mints no credentials,
            // and its tests declare the identity setup would make.
            if platform != Platform::Test
                && resource_entry
                    .config
                    .downcast_ref::<alien_core::ServiceAccount>()
                    .is_some_and(|account| account.extension.is_some())
            {
                errors.push(format!(
                    "Service account '{resource_id}' sets `extension`, which only the identity Alien creates for an extension has. Remove it"
                ));
            }

            if !is_allowed_user_type {
                errors.push(format!(
                    "Resource '{}' has type '{}' which is not allowed. User-defined resources must be one of: {}",
                    resource_id,
                    resource_type,
                    allowed_user_types.iter().map(|s| format!("'{}'", s)).collect::<Vec<_>>().join(", ")
                ));
            }
        }

        errors.extend(extension_type_errors(stack, &custom_resources));

        if errors.is_empty() {
            Ok(CheckResult::success())
        } else {
            Ok(CheckResult::failed(errors))
        }
    }
}

/// Refuses two extensions with one name, a type outside its extension's name, a permission set
/// outside its type, and a custom resource whose type no extension in the stack declares. Types
/// sit under their extension's name, so the first also refuses a type two extensions declare. The
/// last is how a release that drops an extension before its resources fails, so its message names
/// the resources still in the stack.
fn extension_type_errors(
    stack: &Stack,
    custom_resources: &IndexMap<ResourceType, Vec<&str>>,
) -> Vec<String> {
    let mut errors = Vec::new();
    let mut by_name: IndexMap<&str, Vec<String>> = IndexMap::new();
    let mut declared = HashSet::new();
    for extension in &stack.extensions {
        let mut listed = format!("'{}' {}", extension.name, extension.version);
        if !extension.digest.is_empty() {
            listed.push_str(&format!(" ({})", extension.digest));
        }
        by_name.entry(&extension.name).or_default().push(listed);
        for (resource_type, descriptor) in &extension.resource_types {
            declared.insert(resource_type);
            // Each id carries the extension's name, so a customer's security team sees which
            // extension asks for what.
            if !extension.owns(resource_type) {
                let owner = ExtensionManifest::owner_of(resource_type)
                    .map(|owner| format!(", which only an extension named '{owner}' can define"))
                    .unwrap_or_default();
                errors.push(format!(
                    "Extension '{}' declares resource type '{resource_type}'{owner}. Name the type '{}/<type>'",
                    extension.name, extension.name
                ));
            }
            for (platform, services) in &descriptor.services {
                for service in services {
                    if !alien_core::is_cloud_service_name(*platform, service) {
                        errors.push(format!(
                            "Extension '{}' asks for the service '{service}' on {platform} for resource type '{resource_type}', which is not {}",
                            extension.name,
                            match platform {
                                Platform::Gcp => "a GCP API name, '<name>.googleapis.com'",
                                Platform::Azure => "an Azure resource provider, 'Microsoft.<Namespace>'",
                                _ => "a GCP API or an Azure resource provider: Alien enables services only on GCP and Azure",
                            }
                        ));
                    }
                }
            }
            for (flattens, why) in [
                (
                    alien_core::binding_schema::flattens_alternatives
                        as fn(&serde_json::Map<String, serde_json::Value>) -> bool,
                    alien_core::binding_schema::FLATTENED_OPTION,
                ),
                (
                    alien_core::binding_schema::flattens_a_map_beside_fields,
                    alien_core::binding_schema::FLATTENED_MAP,
                ),
            ] {
                if flattens(&descriptor.schemas.outputs) {
                    errors.push(format!(
                        "Extension '{}' declares resource type '{resource_type}' whose outputs {why}",
                        extension.name
                    ));
                }
            }
            // A custom binding carries the resource's outputs beside its own `type` and
            // `service`, so an output with either name could never be bound.
            let outputs = alien_core::binding_schema::output_names(&descriptor.schemas.outputs);
            for name in alien_core::CUSTOM_BINDING_RESERVED_FIELDS {
                if outputs.contains(name) {
                    errors.push(format!(
                        "Extension '{}' gives resource type '{resource_type}' an output named '{name}', which an external binding uses for itself. Rename the output",
                        extension.name
                    ));
                }
            }
            // A link grants the workload sets on the linked resource, so each must be one the
            // type defines: a built-in or another type's id would grant a set this type never
            // declared.
            for id in &descriptor.link.permission_sets {
                if !descriptor.permission_sets.iter().any(|set| &set.id == id) {
                    errors.push(format!(
                        "Extension '{}' links resource type '{resource_type}' with permission set '{id}', which is not one of the type's own permission sets",
                        extension.name
                    ));
                }
            }
            for permission_set in &descriptor.permission_sets {
                if permission_set
                    .id
                    .rsplit_once('/')
                    .map(|(set_type, _)| set_type)
                    != Some(resource_type.as_ref())
                {
                    errors.push(format!(
                        "Extension '{}' defines permission set '{}' for resource type '{resource_type}', but its id is not '{resource_type}/<name>'",
                        extension.name, permission_set.id
                    ));
                }
                // These sets go to the extension's identity, whose credentials reach the
                // extension's controller, which may run outside the customer's cloud, so they may
                // name only permissions Alien has reviewed for a third party.
                let operation = permission_set.id.rsplit('/').next().unwrap_or_default();
                if ["provision", "management", "heartbeat"].contains(&operation) {
                    let grants = alien_permissions::extension_identity_refusals(permission_set);
                    if !grants.is_empty() {
                        errors.push(format!(
                            "Extension '{}' permission set '{}' grants {}. A '{operation}' set goes to the extension's identity and may only name permissions Alien's extension catalog lists, each by its exact name and on the resources it was reviewed for: no wildcard, predefined role or NotResource. Grant data access through a set the type links to workloads; to manage a service the catalog lacks, ask for its actions to be reviewed and added",
                            extension.name,
                            permission_set.id,
                            grants.join(", ")
                        ));
                    }
                }
            }
        }
    }

    let quoted = |names: &[&str]| {
        names
            .iter()
            .map(|name| format!("'{name}'"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    for (name, listed) in &by_name {
        if listed.len() > 1 {
            errors.push(format!(
                "The stack lists more than one extension named '{name}': {}. Keep only one of them",
                listed.join(", ")
            ));
        }
    }
    for (resource_type, resource_ids) in custom_resources {
        if declared.contains(resource_type) {
            continue;
        }
        let extension = resource_type
            .as_ref()
            .split_once('/')
            .map_or(resource_type.as_ref(), |(extension, _)| extension);
        errors.push(format!(
            "Resources {} have type '{resource_type}', which no extension in the stack declares. Add the extension '{extension}' to the stack's extensions, or remove these resources in one release and the extension in the next",
            quoted(resource_ids)
        ));
    }
    errors
}

