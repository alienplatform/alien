// Keeps every name the committed Platform TypeScript SDK exports after Speakeasy
// regenerates it.
//
// Speakeasy names inline models after where they appear in the spec, so a spec
// change can rename, renumber or move them to another module. Published code
// imports them from the package root and from deep module paths. This script
// compares the committed SDK (git HEAD, which generate-typescript-sdk.sh requires
// to be clean before generation) with the regenerated sources, finds each type
// that replaced a published one, and adds an alias for every published name that
// no longer resolves at its published path:
//
// - a name that still exists elsewhere is re-exported from its new module;
// - a renamed type is paired with its replacement by walking both type graphs in
//   parallel from the types whose names survived (same property, same union
//   member), or, for a type nothing references, by identical structure;
// - its schemas, `$Outbound` type and JSON helpers follow the same pairing.
//
// Aliases are appended to generated modules after a marker, and deleted modules
// come back as forwarding modules. Both are rebuilt from scratch on every run.
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const sdkDir = fileURLToPath(new URL("../typescript/", import.meta.url));
const srcDir = path.join(sdkDir, "src");
const require = createRequire(path.join(sdkDir, "package.json"));
const ts = require("typescript");

const forwarderHeader = "// Generated by generate-compatibility-exports.mjs. DO NOT EDIT.\n";
const marker = "\n// Published compatibility exports. Generated by generate-compatibility-exports.mjs.\n";

function sourceFiles(root) {
  return readdirSync(root, { recursive: true })
    .filter(file => /\.tsx?$/.test(file) && !file.endsWith(".d.ts"))
    .map(file => path.join(root, file))
    .sort();
}

// Start from the generated sources alone.
for (const file of sourceFiles(srcDir)) {
  const source = readFileSync(file, "utf8");
  if (source.startsWith(forwarderHeader)) rmSync(file);
  else if (source.includes(marker)) writeFileSync(file, source.split(marker)[0]);
}

// The published sources: the SDK as committed before generation.
const repoRoot = execFileSync("git", ["-C", sdkDir, "rev-parse", "--show-toplevel"], { encoding: "utf8" }).trim();
const publishedDir = mkdtempSync(path.join(tmpdir(), "platform-sdk-published-"));
const archive = execFileSync("git", ["-C", repoRoot, "archive", "HEAD", path.relative(repoRoot, srcDir)], {
  maxBuffer: 1 << 30,
});
execFileSync("tar", ["-x", "-C", publishedDir], { input: archive });
const publishedSrc = path.join(publishedDir, path.relative(repoRoot, srcDir));

// Speakeasy keeps names unique within a directory (`models`, `models/operations`),
// so a declaration is identified by its directory and name.
const qualify = (module, name) => `${path.posix.dirname(module)}/${name}`;
const baseName = id => id.slice(id.lastIndexOf("/") + 1);
const namespace = id => id.slice(0, id.lastIndexOf("/"));

const moduleFor = (module, specifier) =>
  path.posix.normalize(path.posix.join(path.posix.dirname(module), specifier)).replace(/\.js$/, ".ts");

const exported = node => node.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword);

function load(root) {
  const files = sourceFiles(root);
  const program = ts.createProgram(files, {
    noEmit: true,
    allowJs: false,
    skipLibCheck: true,
    types: [],
    module: ts.ModuleKind.Node16,
    moduleResolution: ts.ModuleResolutionKind.Node16,
  });
  const checker = program.getTypeChecker();
  const side = { root, files, checker, types: new Map(), declared: new Map(), lower: new Map(), modules: new Map(), imports: new Map() };
  for (const file of files) {
    const source = program.getSourceFile(file);
    const module = path.relative(root, file).replaceAll(path.sep, "/");
    const imports = new Set();
    for (const statement of source.statements) {
      // Runtime imports, for keeping module evaluation order acyclic.
      const specifier = statement.moduleSpecifier?.text;
      const typeOnly = ts.isImportDeclaration(statement) ? statement.importClause?.isTypeOnly : statement.isTypeOnly;
      if (specifier?.startsWith(".") && !typeOnly) imports.add(moduleFor(module, specifier));
    }
    side.imports.set(module, imports);
    for (const statement of source.statements) {
      if (!exported(statement)) continue;
      const names = ts.isVariableStatement(statement)
        ? statement.declarationList.declarations.map(declaration => declaration.name.getText())
        : statement.name
          ? [statement.name.text]
          : [];
      for (const name of names) {
        side.declared.set(qualify(module, name), module);
        side.lower.set(qualify(module, name.toLowerCase()), qualify(module, name));
      }
      if (ts.isTypeAliasDeclaration(statement) && module.startsWith("models/")) {
        side.types.set(qualify(module, statement.name.text), { decl: statement, module });
      }
    }
    const symbol = checker.getSymbolAtLocation(source);
    const names = new Map();
    for (const symbolExport of symbol ? checker.getExportsOfModule(symbol) : []) {
      const target = symbolExport.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbolExport) : symbolExport;
      const declaration = target.declarations?.[0]?.getSourceFile().fileName;
      const home = declaration && !path.relative(root, declaration).startsWith("..") ? path.relative(root, declaration) : "external/x";
      names.set(symbolExport.getName(), {
        original: qualify(home.replaceAll(path.sep, "/"), target.getName()),
        value: Boolean(target.flags & ts.SymbolFlags.Value),
      });
    }
    side.modules.set(module, names);
  }
  return side;
}

const O = load(publishedSrc);
const N = load(srcDir);

// ---- Pair published types with the types that replaced them. ----

function strip(node) {
  while (ts.isParenthesizedTypeNode(node)) node = node.type;
  return node;
}

function refName(side, node) {
  if (!ts.isTypeReferenceNode(node)) return null;
  let symbol = side.checker.getSymbolAtLocation(node.typeName);
  if (symbol && symbol.flags & ts.SymbolFlags.Alias) symbol = side.checker.getAliasedSymbol(symbol);
  const declaration = symbol?.declarations?.find(ts.isTypeAliasDeclaration);
  if (!declaration) return null;
  const module = path.relative(side.root, declaration.getSourceFile().fileName).replaceAll(path.sep, "/");
  const id = qualify(module, declaration.name.text);
  return side.types.has(id) ? id : null;
}

const members = node => {
  node = strip(node);
  return ts.isUnionTypeNode(node) ? node.types.flatMap(members) : [node];
};
const nullish = node =>
  node.kind === ts.SyntaxKind.UndefinedKeyword ||
  node.kind === ts.SyntaxKind.NullKeyword ||
  (ts.isLiteralTypeNode(node) && node.literal.kind === ts.SyntaxKind.NullKeyword);
const primitive = node =>
  nullish(node) ||
  [ts.SyntaxKind.StringKeyword, ts.SyntaxKind.NumberKeyword, ts.SyntaxKind.BooleanKeyword, ts.SyntaxKind.AnyKeyword, ts.SyntaxKind.UnknownKeyword].includes(node.kind);

function enumValues(side, node) {
  const argument = node.typeArguments?.[0];
  if (!argument || !ts.isTypeQueryNode(argument)) return "";
  let symbol = side.checker.getSymbolAtLocation(argument.exprName);
  if (symbol && symbol.flags & ts.SymbolFlags.Alias) symbol = side.checker.getAliasedSymbol(symbol);
  const initializer = symbol?.valueDeclaration?.initializer;
  return initializer ? [...initializer.getText().matchAll(/:\s*("[^"]*"|-?\d+)/g)].map(match => match[1]).sort().join(",") : "";
}

const isEnum = node => ts.isTypeReferenceNode(node) && /^(ClosedEnum|OpenEnum)$/.test(node.typeName.getText());

// Structure with names erased, for types no surviving type references.
function signature(side, node, stack = new Set()) {
  node = strip(node);
  const name = refName(side, node);
  if (name) {
    if (stack.has(name) || stack.size > 12) return "@";
    stack.add(name);
    const result = signature(side, side.types.get(name).decl.type, stack);
    stack.delete(name);
    return result;
  }
  if (ts.isTypeLiteralNode(node)) {
    return `{${node.members
      .map(member => `${member.name ? member.name.getText() : "[]"}${member.questionToken ? "?" : ""}:${member.type ? signature(side, member.type, stack) : ""}`)
      .sort()
      .join(",")}}`;
  }
  if (ts.isUnionTypeNode(node)) return `(${node.types.map(type => signature(side, type, stack)).sort().join("|")})`;
  if (ts.isArrayTypeNode(node)) return `${signature(side, node.elementType, stack)}[]`;
  if (isEnum(node)) return `enum(${enumValues(side, node)})`;
  if (ts.isTypeReferenceNode(node) && node.typeArguments) {
    return `${node.typeName.getText()}<${node.typeArguments.map(type => signature(side, type, stack)).join(",")}>`;
  }
  return node.getText();
}

// A union written inline names the same members as its declared union alias.
function unionKey(side, node) {
  const all = members(node).filter(member => !nullish(member));
  if (all.length < 2) return null;
  const names = all.map(member => (primitive(member) ? `:${member.getText()}` : refName(side, member)));
  if (names.some(name => !name) || names.every(name => name.startsWith(":"))) return null;
  return names.sort().join("|");
}
for (const side of [O, N]) {
  side.unions = new Map();
  for (const [name, { decl }] of side.types) {
    const key = !baseName(name).includes("$") && unionKey(side, decl.type);
    if (key && !side.unions.has(key)) side.unions.set(key, name);
  }
}
const unionAlias = (side, node) => {
  const key = unionKey(side, node);
  return key ? (side.unions.get(key) ?? null) : null;
};

function shape(side, node, depth = 0) {
  node = strip(node);
  const name = refName(side, node);
  if (name && depth < 3) return shape(side, side.types.get(name).decl.type, depth + 1);
  if (ts.isTypeLiteralNode(node)) {
    const properties = new Set();
    const literals = new Set();
    for (const member of node.members) {
      if (!member.name) continue;
      properties.add(member.name.getText());
      if (member.type && ts.isLiteralTypeNode(member.type)) literals.add(`${member.name.getText()}=${member.type.getText()}`);
    }
    return { kind: "object", properties, literals };
  }
  if (ts.isArrayTypeNode(node)) return { kind: "array" };
  if (isEnum(node)) return { kind: "enum", values: new Set(enumValues(side, node).split(",")) };
  return { kind: "other", text: node.getText() };
}

function similarity(a, b) {
  if (a.kind !== b.kind) return -1;
  const jaccard = (x, y) => {
    const union = new Set([...x, ...y]).size;
    return union ? [...x].filter(value => y.has(value)).length / union : 1;
  };
  if (a.kind === "object") {
    let score = jaccard(a.properties, b.properties);
    for (const literal of a.literals) {
      if (b.literals.has(literal)) score += 10;
      else if ([...b.literals].some(other => other.split("=")[0] === literal.split("=")[0])) score -= 20;
    }
    return score;
  }
  if (a.kind === "enum") return jaccard(a.values, b.values);
  return a.kind === "array" || a.text === b.text ? 1 : 0;
}

const votes = new Map();
function vote(published, current) {
  if (!votes.has(published)) votes.set(published, new Map());
  const counts = votes.get(published);
  counts.set(current, (counts.get(current) ?? 0) + 1);
}

const walked = new Set();
function walk(before, after) {
  before = strip(before);
  after = strip(after);
  const beforeName = refName(O, before);
  const afterName = refName(N, after);
  if (beforeName && afterName) {
    vote(beforeName, afterName);
    const key = `${beforeName}|${afterName}`;
    if (walked.has(key)) return;
    walked.add(key);
    return walk(O.types.get(beforeName).decl.type, N.types.get(afterName).decl.type);
  }
  if (beforeName) {
    const alias = unionAlias(N, after);
    if (alias) vote(beforeName, alias);
    return walk(O.types.get(beforeName).decl.type, after);
  }
  if (afterName) {
    const alias = unionAlias(O, before);
    if (alias) vote(alias, afterName);
    return walk(before, N.types.get(afterName).decl.type);
  }
  const beforeUnion = unionAlias(O, before);
  const afterUnion = unionAlias(N, after);
  if (beforeUnion && afterUnion) vote(beforeUnion, afterUnion);
  if (ts.isTypeLiteralNode(before) && ts.isTypeLiteralNode(after)) {
    const properties = new Map(after.members.filter(member => member.name).map(member => [member.name.getText(), member]));
    for (const member of before.members) {
      const other = member.name ? properties.get(member.name.getText()) : after.members.find(ts.isIndexSignatureDeclaration);
      if (member.type && other?.type) walk(member.type, other.type);
    }
    return;
  }
  if (ts.isArrayTypeNode(before) && ts.isArrayTypeNode(after)) return walk(before.elementType, after.elementType);
  if (ts.isTypeReferenceNode(before) && ts.isTypeReferenceNode(after) && before.typeArguments && after.typeArguments) {
    before.typeArguments.forEach((argument, index) => after.typeArguments[index] && walk(argument, after.typeArguments[index]));
    return;
  }
  const beforeMembers = members(before).filter(member => !primitive(member));
  const afterMembers = members(after).filter(member => !primitive(member));
  if (beforeMembers.length === 1 && afterMembers.length === 1) {
    if (beforeMembers[0] !== before || afterMembers[0] !== after) walk(beforeMembers[0], afterMembers[0]);
    return;
  }
  // Pair union members by discriminator values, then by shared properties.
  const beforeShapes = beforeMembers.map(member => shape(O, member));
  const afterShapes = afterMembers.map(member => shape(N, member));
  const pairs = [];
  beforeShapes.forEach((a, i) => afterShapes.forEach((b, j) => pairs.push([similarity(a, b), i, j])));
  pairs.sort((a, b) => b[0] - a[0] || a[1] - b[1] || a[2] - b[2]);
  const usedBefore = new Set();
  const usedAfter = new Set();
  for (const [score, i, j] of pairs) {
    if (score <= 0 || usedBefore.has(i) || usedAfter.has(j)) continue;
    usedBefore.add(i);
    usedAfter.add(j);
    walk(beforeMembers[i], afterMembers[j]);
  }
}

for (const [name, { decl }] of O.types) {
  const current = N.types.get(name);
  if (current) walk(decl.type, current.decl.type);
}

const bySignature = new Map();
for (const [name, { decl }] of N.types) {
  if (baseName(name).includes("$")) continue;
  const key = signature(N, decl.type);
  if (!bySignature.has(key)) bySignature.set(key, []);
  bySignature.get(key).push(name);
}
const withoutNumber = id => baseName(id).replace(/\d+$/, "");

const replacements = new Map();
for (const [name, { decl }] of O.types) {
  if (baseName(name).includes("$") || N.types.has(name)) continue;
  const counts = votes.get(name);
  if (counts) {
    replacements.set(name, [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0][0]);
    continue;
  }
  const candidates = bySignature.get(signature(O, decl.type)) ?? [];
  const pick =
    candidates.find(candidate => withoutNumber(candidate) === withoutNumber(name)) ??
    candidates.find(candidate => baseName(candidate).startsWith(withoutNumber(name))) ??
    [...candidates].sort()[0];
  if (pick) replacements.set(name, pick);
}

// ---- Resolve each published export to a current declaration. ----

// Generated companions of a model: schemas, the `$Outbound` type and JSON helpers.
const suffixes = ["$inboundSchema", "$outboundSchema", "$Outbound", "FromJSON", "ToJSON"];
function split(id) {
  const name = baseName(id);
  for (const suffix of suffixes) {
    if (!name.endsWith(suffix) || name === suffix) continue;
    const base = `${namespace(id)}/${name.slice(0, -suffix.length)}`;
    const model = O.types.has(base) ? base : O.lower.get(base.toLowerCase().replace(/^.*\//, `${namespace(id)}/`));
    if (model && O.types.has(model)) return { model, suffix };
  }
  return O.types.has(id) ? { model: id, suffix: "" } : null;
}
function companion(model, suffix, value) {
  const candidate = `${model}${suffix}`;
  const id = suffix.endsWith("JSON")
    ? N.lower.get(`${namespace(model)}/${baseName(candidate).toLowerCase()}`)
    : candidate;
  if (!id || !N.declared.has(id)) return null;
  return value && !isValue(id) ? null : id;
}
function isValue(id) {
  return Boolean(N.modules.get(N.declared.get(id))?.get(baseName(id))?.value);
}

// Every current declaration that can stand in for a published one, best first:
// the same declaration, the paired replacement's companion, then the companions
// of structurally identical models (for example, when the replacement is now only
// returned and has no request schema).
function candidates(original, value) {
  const found = [];
  if (N.declared.has(original) && (!value || isValue(original))) found.push(original);
  const parts = split(original);
  const model = parts && (N.types.has(parts.model) ? parts.model : replacements.get(parts.model));
  if (model) {
    const direct = companion(model, parts.suffix, value);
    if (direct) found.push(direct);
    for (const key of [signature(N, N.types.get(model).decl.type), signature(O, O.types.get(parts.model).decl.type)]) {
      for (const candidate of bySignature.get(key) ?? []) {
        const name = companion(candidate, parts.suffix, value);
        if (name) found.push(name);
      }
    }
  }
  return [...new Set(found)];
}

// A value alias imports its home module. Never let that close an import cycle:
// a module evaluated before its dependency would read an uninitialized schema.
const imports = new Map([...N.imports].map(([module, targets]) => [module, new Set(targets)]));
function reaches(from, to) {
  const seen = new Set([from]);
  const queue = [from];
  while (queue.length) {
    const module = queue.pop();
    if (module === to) return true;
    for (const next of imports.get(module) ?? []) {
      if (!seen.has(next)) {
        seen.add(next);
        queue.push(next);
      }
    }
  }
  return false;
}
function pick(module, options, value) {
  for (const id of options) {
    const home = N.declared.get(id);
    if (!value || home === module || imports.get(module)?.has(home)) return id;
    if (!reaches(home, module)) {
      if (!imports.has(module)) imports.set(module, new Set());
      imports.get(module).add(home);
      return id;
    }
  }
  return null;
}

const additions = new Map();
const unresolved = [];
for (const [module, names] of O.modules) {
  const current = N.modules.get(module);
  for (const [name, { original, value }] of names) {
    if (current?.has(name) && (!value || current.get(name).value)) continue;
    const target = pick(module, candidates(original, value), value);
    if (!target) {
      unresolved.push(`${module}: ${name}`);
      continue;
    }
    if (!additions.has(module)) additions.set(module, []);
    additions.get(module).push({ name, target, home: N.declared.get(target), value });
  }
}

if (unresolved.length) {
  console.error(`${unresolved.length} published exports have no current equivalent:`);
  for (const line of unresolved.slice(0, 100)) console.error(`  ${line}`);
  process.exit(1);
}

// Keep the output small: a name a module already gets through `export *` needs
// no alias of its own, and a forwarding module re-exports the module that
// provides most of its names.
const added = new Map(
  [...additions].map(([module, entries]) => [module, new Map(entries.map(entry => [entry.name, entry.target]))]),
);
const provides = (module, name, target) =>
  N.modules.get(module)?.get(name)?.original === target || added.get(module)?.get(name) === target;
const specifierFor = (module, home) => {
  const specifier = path.posix.relative(path.posix.dirname(module), home).replace(/\.tsx?$/, ".js");
  return specifier.startsWith(".") ? specifier : `./${specifier}`;
};
const finalCache = new Map();
function finalExports(module) {
  if (!finalCache.has(module)) {
    const names = new Map([...(N.modules.get(module) ?? [])].map(([name, { original }]) => [name, original]));
    for (const [name, target] of added.get(module) ?? []) names.set(name, target);
    finalCache.set(module, names);
  }
  return finalCache.get(module);
}
const stars = new Map();
for (const [module, entries] of additions) {
  let starred = [];
  if (N.modules.has(module)) {
    const source = readFileSync(path.join(srcDir, module), "utf8");
    starred = [...source.matchAll(/^export \* from "([^"]+)";$/gm)].map(match => moduleFor(module, match[1]));
  } else {
    const counts = new Map();
    for (const { name, target, home } of entries) {
      if (baseName(target) === name) counts.set(home, (counts.get(home) ?? 0) + 1);
    }
    // Star-export the modules that provide the most names, as long as no two of
    // them export the same name with different meanings.
    for (const [home, count] of [...counts].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))) {
      if (count < 20 && starred.length) break;
      const names = finalExports(home);
      const conflict = starred.some(other => {
        const otherNames = finalExports(other);
        for (const [name, original] of names) if (otherNames.has(name) && otherNames.get(name) !== original) return true;
        return false;
      });
      if (!conflict) starred.push(home);
    }
    stars.set(module, starred);
  }
  additions.set(
    module,
    entries.filter(({ name, target }) => !starred.some(other => other !== module && provides(other, name, target))),
  );
}

for (const [module, entries] of additions) {
  const file = path.join(srcDir, module);
  const lines = entries
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(({ name, target, home, value }) => {
      const binding = baseName(target) === name ? name : `${baseName(target)} as ${name}`;
      const keyword = value ? "export" : "export type";
      if (home === module) return `${keyword} { ${binding} };`;
      return `${keyword} { ${binding} } from "${specifierFor(module, home)}";`;
    });
  if (N.modules.has(module)) {
    if (lines.length) writeFileSync(file, `${readFileSync(file, "utf8").trimEnd()}\n${marker}${lines.join("\n")}\n`);
  } else {
    const star = [...(stars.get(module) ?? [])].sort().map(home => `export * from "${specifierFor(module, home)}";`);
    writeFileSync(file, `${forwarderHeader}${[...star, ...lines].join("\n")}\n`);
  }
}

rmSync(publishedDir, { recursive: true, force: true });
const aliases = [...additions.values()].reduce((total, entries) => total + entries.length, 0);
console.log(
  `Compatibility exports: ${replacements.size} renamed models paired, ${aliases} aliases in ${additions.size} modules ` +
    `(${[...additions.keys()].filter(module => !N.modules.has(module)).length} forwarding modules).`,
);
