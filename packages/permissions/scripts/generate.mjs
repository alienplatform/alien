import { execFileSync } from "node:child_process"
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { homedir, tmpdir } from "node:os"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../../..")
const output = resolve(root, "packages/permissions/generated")
const temporary = mkdtempSync(resolve(tmpdir(), "alien-permissions-"))
try {
  execFileSync(
    "cargo",
    [
      "+1.97.1",
      "build",
      "--locked",
      "--release",
      "-p",
      "alien-permissions",
      "--no-default-features",
      "--features",
      "wasm",
      "--target",
      "wasm32-unknown-unknown",
    ],
    {
      cwd: root,
      stdio: "inherit",
      env: {
        ...process.env,
        CARGO_PROFILE_RELEASE_OPT_LEVEL: "z",
        CARGO_PROFILE_RELEASE_LTO: "true",
        CARGO_PROFILE_RELEASE_CODEGEN_UNITS: "1",
        CARGO_PROFILE_RELEASE_PANIC: "abort",
        CARGO_PROFILE_RELEASE_STRIP: "symbols",
        RUSTFLAGS: `--remap-path-prefix=${root}=. --remap-path-prefix=${homedir()}=/build`,
      },
    },
  )
  const target = resolve(root, process.env.CARGO_TARGET_DIR ?? "target")
  execFileSync(
    "wasm-bindgen",
    [
      resolve(target, "wasm32-unknown-unknown/release/alien_permissions.wasm"),
      "--target",
      "web",
      "--omit-default-module-path",
      "--out-dir",
      temporary,
      "--out-name",
      "compiler",
    ],
    { stdio: "inherit" },
  )
  mkdirSync(output, { recursive: true })
  for (const name of ["compiler.js", "compiler.d.ts"])
    writeFileSync(resolve(output, name), readFileSync(resolve(temporary, name)))
  const bytes = readFileSync(resolve(temporary, "compiler_bg.wasm"))
  writeFileSync(
    resolve(output, "bytes.js"),
    `// Generated by pnpm generate.\nexport const bytes = "${bytes.toString("base64")}"\n`,
  )
} finally {
  rmSync(temporary, { recursive: true, force: true })
}
